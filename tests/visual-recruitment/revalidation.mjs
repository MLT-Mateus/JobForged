import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.TEST_BROWSER?{executablePath:process.env.TEST_BROWSER}:{})});
const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
const errors=[],passed=[];page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(10000);
const base=process.env.RECRUITMENT_PREVIEW||'http://127.0.0.1:5185/recruitment';
const out='outputs/recruitment-revalidation';await fs.mkdir(out,{recursive:true});
const check=(name,condition)=>{assert.ok(condition,name);passed.push(name)};
try{
 await page.goto(base+'?view=editor&new');await page.locator('.job-editor-fields').waitFor();
 check('mobile readiness is compact',await page.locator('.jf-readiness-details').isHidden());
 check('next missing field is visible',await page.getByRole('button',{name:'Próximo: Cargo',exact:true}).isVisible());
 await page.getByRole('button',{name:'Ver pendências',exact:true}).click();
 check('mobile can expand all missing fields',await page.locator('.jf-readiness-details').isVisible());
 await page.screenshot({path:out+'/mobile-readiness-expanded.png'});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'?view=editor');await page.locator('.job-editor-fields').waitFor();
 await page.getByLabel('Horário ou escala',{exact:true}).fill('');
 await page.locator('.jf-readiness-details').getByRole('button',{name:'Jornada',exact:true}).click();
 await page.waitForTimeout(100);
 check('journey issue focuses missing schedule',await page.getByLabel('Horário ou escala',{exact:true}).evaluate(e=>document.activeElement===e));
 await page.getByLabel('Horário ou escala',{exact:true}).fill('9h às 18h');
 await page.locator('.job-editor-aside nav button').nth(1).click();
 const optional=page.locator('details').filter({has:page.locator('summary').filter({hasText:'Prazos e contato'})});
 await optional.locator('summary').click();await page.getByLabel('E-mail público',{exact:true}).fill('invalid');await optional.locator('summary').click();
 await page.locator('.jf-readiness-details').getByRole('button',{name:'Corrija o e-mail de contato ou remova este complemento.',exact:true}).click();
 await page.waitForTimeout(100);
 check('invalid optional field expands its section and receives focus',await page.getByLabel('E-mail público',{exact:true}).evaluate(e=>document.activeElement===e));
 await page.getByLabel('E-mail público',{exact:true}).fill('');
 await page.locator('.job-editor-aside nav button').nth(2).click();await page.getByRole('checkbox',{name:'Aceitar candidaturas após publicar',exact:true}).uncheck();
 const request=page.waitForRequest(r=>r.url().endsWith('/api/company/jobs')&&r.method()==='POST'&&r.postDataJSON().operation==='save');
 await page.getByRole('button',{name:'Publicar',exact:true}).click();
 check('acceptance belongs to saved revision',(await request).postDataJSON().document.acceptApplications===false);
 await page.getByRole('link',{name:'Ver candidaturas',exact:true}).waitFor();
 check('publication offers direct next actions',await page.getByRole('link',{name:'Abrir página',exact:true}).isVisible());
 await page.screenshot({path:out+'/published-actions-isolated.png'});
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'?application=73000000-0000-4000-8000-000000000002');
 await page.getByRole('button',{name:'Ver currículo',exact:true}).click();
 await page.locator('.jf-pdf-preview canvas').waitFor();
 check('private PDF renders without native viewer',await page.locator('.jf-pdf-preview canvas').count()===1&&await page.locator('.jf-pdf-preview iframe').count()===0);
 await page.getByRole('button',{name:'Próxima',exact:true}).click();
 await page.locator('.jf-pdf-preview summary').click();
 await page.getByText('Experiencia sintetica - pagina dois',{exact:true}).waitFor();
 check('PDF pagination and accessible text work',await page.getByText('Página 2 de 2',{exact:true}).isVisible());
 check('PDF does not overflow mobile',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:out+'/pdf-mobile-page-two.png'});
 await page.route('**/api/company/operations?operation=resume*',route=>route.fulfill({status:200,contentType:'application/pdf',body:'invalid PDF'}));
 await page.getByRole('button',{name:'Ver currículo',exact:true}).click();
 await page.locator('.jf-pdf-preview [role=alert]').waitFor();
 check('invalid PDF has recoverable fallback',await page.getByRole('link',{name:'Baixar',exact:true}).isVisible());
 check('no runtime errors',errors.length===0);
}finally{await fs.writeFile(out+'/revalidation-checks.json',JSON.stringify({passed,errors},null,2));console.log(JSON.stringify({passed,errors}));await browser.close()}
